"""Independent balanced pairing of post-DA particles and historical weather.

ESP members were generated by independently balancing and randomly pairing
selections from the post-DA state ensemble and the eligible historical
meteorological ensemble. This approximates their product distribution while
limiting ensemble size.

A particle is one item. Its SUMMA restart and mizuRoute restart stay bound
through sampling, copying, and the forecast run.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path
from typing import Sequence

import numpy as np

ESP_SAMPLING_DESCRIPTION = (
    "ESP members were generated by independently balancing and randomly pairing "
    "selections from the post-DA state ensemble and the eligible historical "
    "meteorological ensemble. This approximates their product distribution while "
    "limiting ensemble size."
)

INITIALIZATION_INCREMENTAL = "incremental"
INITIALIZATION_BALANCED = "balanced_independent"
ESP_INITIALIZATIONS = (INITIALIZATION_INCREMENTAL, INITIALIZATION_BALANCED)

_SUMMA_RESTART_DATE_RE = re.compile(r"_(\d{10})")
_MIZU_RESTART_DATE_RE = re.compile(r"\.r\.(\d{4}-\d{2}-\d{2})-")


@dataclass(frozen=True)
class ParticleState:
    """One post-DA particle: SUMMA and mizuRoute restarts from the same donor."""

    label: str
    donor_label: str
    summa_restart: str
    mizuroute_restart: str | None
    weight: float
    file_manager: str
    resampled: bool


@dataclass(frozen=True)
class ForecastAssignment:
    """One forecast member, already paired and identified."""

    forecast_id: str
    particle: ParticleState
    trace_year: int
    weighting: str


def post_da_catalog_path(run_dir: Path, when: datetime) -> Path:
    return Path(run_dir) / "assimilation" / f"post_da_{when.strftime('%Y%m%d%H')}.json"


def write_post_da_catalog(
    run_dir: Path,
    when: datetime,
    particles: Sequence[ParticleState],
) -> Path:
    """Write one catalog record per particle, with both restarts on that record."""
    if not particles:
        raise ValueError(f"Cannot write an empty post-DA catalog for {when}.")
    for particle in particles:
        validate_particle_binding(particle, when, require_routing=False)
    path = post_da_catalog_path(run_dir, when)
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "issue_time": when.strftime("%Y-%m-%d %H:%M"),
        "description": (
            "Each particle binds one SUMMA restart to the mizuRoute restart "
            "from the same donor. Do not pair those files independently."
        ),
        "particles": [asdict(particle) for particle in particles],
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return path


def read_post_da_catalog(path: Path) -> list[ParticleState]:
    try:
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise
    except json.JSONDecodeError as exc:
        raise ValueError(f"Post-DA catalog is not valid JSON: {path}") from exc
    raw_particles = payload.get("particles")
    if not isinstance(raw_particles, list) or not raw_particles:
        raise ValueError(f"Post-DA catalog {path} has no particles.")
    particles: list[ParticleState] = []
    labels: set[str] = set()
    for item in raw_particles:
        if not isinstance(item, dict):
            raise ValueError(f"Post-DA catalog {path} has a particle that is not an object.")
        try:
            particle = ParticleState(
                label=str(item["label"]),
                donor_label=str(item["donor_label"]),
                summa_restart=str(item["summa_restart"]),
                mizuroute_restart=(
                    None
                    if item.get("mizuroute_restart") in (None, "")
                    else str(item["mizuroute_restart"])
                ),
                weight=float(item["weight"]),
                file_manager=str(item["file_manager"]),
                resampled=bool(item["resampled"]),
            )
        except KeyError as exc:
            raise ValueError(f"Post-DA catalog {path} is missing {exc}.") from exc
        if particle.label in labels:
            raise ValueError(
                f"Post-DA catalog {path} lists particle {particle.label} more than once."
            )
        labels.add(particle.label)
        particles.append(particle)
    return particles


def summa_restart_date_key(path: Path) -> str:
    match = _SUMMA_RESTART_DATE_RE.search(Path(path).name)
    if not match:
        raise ValueError(f"SUMMA restart name has no date token: {path}")
    return match.group(1)


def mizuroute_restart_day(path: Path) -> str:
    match = _MIZU_RESTART_DATE_RE.search(Path(path).name)
    if not match:
        raise ValueError(f"mizuRoute restart name has no date token: {path}")
    return match.group(1)


def validate_particle_binding(
    particle: ParticleState,
    when: datetime,
    *,
    require_routing: bool,
) -> None:
    """Require the SUMMA and mizuRoute files to be the same particle at ``when``.

    This checks names and presence only. It does not open or edit state values.
    """
    issue_key = when.strftime("%Y%m%d%H")
    issue_day = when.strftime("%Y-%m-%d")
    summa_path = Path(particle.summa_restart)
    if not summa_path.is_file():
        raise FileNotFoundError(
            f"Post-DA SUMMA restart for particle {particle.label} is missing: {summa_path}"
        )
    summa_key = summa_restart_date_key(summa_path)
    if summa_key != issue_key:
        raise ValueError(
            f"SUMMA restart {summa_path.name} for particle {particle.label} "
            f"is dated {summa_key}, not the forecast issue {issue_key}."
        )
    if require_routing and not particle.mizuroute_restart:
        raise FileNotFoundError(
            f"Post-DA particle {particle.label} has a SUMMA restart but no "
            "matching mizuRoute restart."
        )
    if not particle.mizuroute_restart:
        return
    route_path = Path(particle.mizuroute_restart)
    if not route_path.is_file():
        raise FileNotFoundError(
            f"Post-DA mizuRoute restart for particle {particle.label} is missing: {route_path}"
        )
    route_day = mizuroute_restart_day(route_path)
    if route_day != issue_day:
        raise ValueError(
            f"mizuRoute restart {route_path.name} for particle {particle.label} "
            f"is dated {route_day}, which does not match SUMMA restart {summa_path.name}."
        )


def weighting_mode(particles: Sequence[ParticleState]) -> str:
    """Equal-count balance only when the posterior particles are equally weighted.

    SIR resampling already turned the posterior into an equally weighted
    multiset. Those saved pre-resample weights are not applied again.
    """
    if not particles:
        raise ValueError("Post-DA state pool is empty.")
    if any(particle.resampled for particle in particles) and not all(
        particle.resampled for particle in particles
    ):
        raise ValueError("Post-DA catalog mixes resampled and unresampled particles.")
    if all(particle.resampled for particle in particles):
        return "equal"
    weights = np.asarray([particle.weight for particle in particles], dtype=float)
    _validate_weights(weights)
    if np.allclose(weights, weights[0]):
        return "equal"
    return "systematic"


def balanced_indices(n_pool: int, n_draw: int, rng: np.random.Generator) -> np.ndarray:
    """Draw ``n_draw`` indices so each item appears ``floor`` or ``ceil`` times."""
    if n_pool < 1:
        raise ValueError("Cannot sample from an empty pool.")
    if n_draw < 1:
        raise ValueError("n_members must be >= 1.")
    base = n_draw // n_pool
    extra = n_draw % n_pool
    indices = np.repeat(np.arange(n_pool, dtype=int), base)
    if extra:
        extra_indices = np.asarray(rng.choice(n_pool, size=extra, replace=False), dtype=int)
        indices = np.concatenate([indices, extra_indices])
    rng.shuffle(indices)
    return indices


def systematic_indices(weights: np.ndarray, n_draw: int, rng: np.random.Generator) -> np.ndarray:
    """Systematic resampling, then a shuffle on the same stream."""
    if n_draw < 1:
        raise ValueError("n_members must be >= 1.")
    validated = _validate_weights(weights)
    cdf = np.cumsum(validated)
    cdf[-1] = 1.0
    offset = float(rng.random()) / n_draw
    positions = offset + (np.arange(n_draw, dtype=float) / n_draw)
    indices = np.searchsorted(cdf, positions, side="left")
    indices = np.clip(indices, 0, validated.size - 1).astype(int)
    rng.shuffle(indices)
    return indices


def sample_forecast_members(
    particles: Sequence[ParticleState],
    trace_years: Sequence[int],
    *,
    n_members: int,
    seed: int,
    issue_key: str,
    weighting: str | None = None,
) -> list[ForecastAssignment]:
    """Pair N particles with N weather years using independent random streams.

    Selecting a particle index selects that particle's SUMMA restart and its
    mizuRoute restart together. Weather years are shuffled on a different stream.
    """
    if n_members < 1:
        raise ValueError("n_members must be >= 1.")
    if seed < 0:
        raise ValueError("ESP sampling seed must be >= 0.")
    if not particles:
        raise ValueError("Post-DA state pool is empty.")
    if not trace_years:
        raise ValueError("Historical weather pool is empty.")
    mode = weighting or weighting_mode(particles)
    if mode not in {"equal", "systematic"}:
        raise ValueError(f"Unsupported ESP weighting mode {mode!r}.")
    state_rng, weather_rng = _issue_streams(seed, issue_key)
    if mode == "equal":
        state_index = balanced_indices(len(particles), n_members, state_rng)
    else:
        weights = np.asarray([particle.weight for particle in particles], dtype=float)
        state_index = systematic_indices(weights, n_members, state_rng)
    weather_index = balanced_indices(len(trace_years), n_members, weather_rng)
    years = list(trace_years)
    assignments: list[ForecastAssignment] = []
    for position, (state_at, weather_at) in enumerate(zip(state_index, weather_index)):
        particle = particles[int(state_at)]
        assignments.append(
            ForecastAssignment(
                forecast_id=f"m{position + 1:03d}",
                particle=particle,
                trace_year=int(years[int(weather_at)]),
                weighting=mode,
            )
        )
    return assignments


def _issue_streams(seed: int, issue_key: str) -> tuple[np.random.Generator, np.random.Generator]:
    sequence = np.random.SeedSequence([int(seed), int(issue_key)])
    state_sequence, weather_sequence = sequence.spawn(2)
    return np.random.default_rng(state_sequence), np.random.default_rng(weather_sequence)


def _validate_weights(weights: np.ndarray) -> np.ndarray:
    values = np.asarray(weights, dtype=float)
    if values.ndim != 1 or values.size < 1:
        raise ValueError("Weights must be a non-empty 1-D array.")
    if not np.isfinite(values).all():
        raise ValueError("Weights must be finite.")
    if np.any(values < 0):
        raise ValueError("Weights must be non-negative.")
    total = float(values.sum())
    if total <= 0:
        raise ValueError("Weights must sum to a positive value.")
    return values / total
