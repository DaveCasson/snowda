    @timer
    def read_swe_data(self):
        """Reads SWE measurement values from a prepared netCDF file

        Parameters
        ----------
        Properties read in from configuration

        input_swe_hru_nc: str
            netcdf file containing measured SWE values per HRU
            Generated by the modeller, using script such as ECCCSnowDataReader
        start_time : datetime object
            model start time
        end_time: datetime object
            model end time

        Returns
        -------
        swe_hru_ds : dataset
            xarray dataset of all measured values for the model run

        TODO: None at the moment

        """
        # Open NetCDF dataset
        swe_hru_ds_complete = xr.open_dataset(self.input_swe_hru_nc)

        #Convert date time objects to correct string format for slice
        start_time_slice = self.start_time.strftime("%Y-%m-%d")
        end_time_slice   = self.end_time.strftime("%Y-%m-%d")

        #Truncate dataset to model run time
        swe_hru_ds = swe_hru_ds_complete.sel(time=slice(start_time_slice,end_time_slice))

        #Drop any HRUs that have no data
        swe_hru_ds = swe_hru_ds.dropna('hru', how='all')

        #Convert to DataFrame
        swe_hru_df = swe_hru_ds.to_dataframe()
        swe_hru_df.index.names = ['hru', 'time']
        swe_hru_df.columns = ['meas_snw']

        # Return list of unique HRU values
        hru_list = swe_hru_df.index.unique(level='hru').values  # hru_list is a list of hru ids
        hru_index = self.get_hru_index(hru_list)  # hru_index is the corresponding index of those values

        self.swe_hru_df = swe_hru_df
        self.hru_index  = hru_index

        return

    @timer
    def read_particles(self,particle_files, particle_variable, hru_index,end_date_current_run,ens_label_array):
        """Reads the values from model state files based on the variable defined

        Parameters
        ----------
        particle_files : list
            List of all output state files generated by the model run
        particle_variable : str
            The variable to be extracted from the model run file
        hru_list: list
            List of HRU values to be compared against

        Returns
        -------
        particles : DataFrame
            Dataframe values for each data point, from each file

        TODO: Improve documentation
        """

        particles_dict = {}
        for hru_index,hru_id in zip(hru_index['hru_index'],hru_index['hruId']):
            particles = []
            for particle_file in particle_files:
                particle_ds = xr.open_dataset(particle_file)
                particles.append(particle_ds[particle_variable].sel(hru=hru_index).values)
                particle_ds.close()
            particles_dict[hru_id] = np.hstack(particles)

        particles_df = pd.DataFrame.from_dict(particles_dict,orient='index')

        #Structure particle dataframe for output
        particles_df["time"] = end_date_current_run
        particles_df.reset_index(inplace=True)
        particles_df.set_index(['index', 'time'], inplace=True)
        particles_df.index.names = ['hru', 'time']
        particles_df.columns = ens_label_array

        return particles_df


    def read_summa_ens_output(self,variable,file_suffix):
        """Reads the multi-file output of a summa run, and returns a dataframe of all values
           for a specific variable

        Parameters
        ----------
        self : object
            Object containing summa run configuration items set in the run config file
        variable : str
            The variable to be extracted from the model run file
        file_suffix : str
            File suffix for the output files to be read (i.e. day in day.nc)

        Returns
        -------
        ens_result_df : DataFrame
            Dataframe of each all ensemble runs for the variable

        TODO: None
        """

        ens_list = self.ens_label_array

        # Write file patterns to read for each ensemble (i.e. file
        model_files_ens_list = [f"{self.output_dir}/{ens_label}*{file_suffix}.nc" for ens_label in ens_list]

        model_ens_df = []
        for model_files, ens_label in zip(model_files_ens_list, ens_list):
            logging.info(f'Reading {variable} from {ens_label}')
            model_ds = xr.open_mfdataset(model_files)
            model_var_df = model_ds[variable]
            model_var_df = model_var_df.to_dataframe()
            model_ds.close()
            model_var_df.columns = [ens_label]
            model_ens_df.append(model_var_df)

        ens_result_df = pd.concat(model_ens_df,axis=1)
        ens_result_df = ens_result_df.swaplevel().sort_values('hru')

        return ens_result_df

